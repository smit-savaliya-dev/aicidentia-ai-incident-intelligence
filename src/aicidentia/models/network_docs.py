"""Build docs/rq2_network.md from the Phase 5 results."""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from aicidentia.config import load_config
from aicidentia.data.audit_docs import n, pct
from aicidentia.models.network_outputs import NetworkResults
from aicidentia.viz.style import to_markdown

logger = logging.getLogger(__name__)
_TYPE_NAME = {
    "organisation": "organisations",
    "ai_system": "AI systems",
    "harmed_group": "harmed groups",
}


def _figure(name: str, caption: str, snapshot: str) -> str:
    return f"![{caption}](../reports/figures/{name}.png)\n\n*Figure: {caption}. Source: AIID snapshot {snapshot}.*\n"


def _centrality_view(table: pd.DataFrame) -> pd.DataFrame:
    out = table.copy()
    out["betweenness"] = out["betweenness"].round(0).astype(int)
    for col in ("pagerank", "eigenvector"):
        out[col] = out[col].round(4)
    return out.rename(columns={"label": "alleged involvement: entity", "n_incidents": "incidents"})


def write_network_doc(res: NetworkResults, path: Path) -> None:
    """Write docs/rq2_network.md."""
    cfg = load_config()["network"]
    snap = str(load_config()["snapshot_date"])
    f = res.facts
    ms = res.method_summary.set_index("method")
    ch = ms.loc[res.chosen_method]
    rob = res.robustness
    hs = f["hetero_nodes_by_type"]
    prof = res.profile
    sizes = f["community_sizes"]
    largest_share = max(sizes.values()) / sum(sizes.values())
    lpa = ms.loc["label_propagation"]
    other = ms.drop(index=res.chosen_method)["modularity_mean"].idxmax()

    L: list[str] = []
    add = L.append
    add("# RQ2: the incident network (Phase 5)\n")
    add(
        f"_Auto-generated by `aicidentia.models.network_outputs` (AIID snapshot **{snap}**). Numbers are registered in `reports/results.json` under `rq2.*`. "
        "Organisations are **alleged** deployers and developers as AIID records them; centrality is frequency of involvement in reported incidents, never blame._\n"
    )
    add("## Summary\n")
    add(
        f"- **Network:** {n(f['hetero_nodes'])} nodes and {n(f['hetero_edges'])} edges in the typed incident graph "
        f"({n(hs['incident'])} incidents, {n(hs.get('organisation', 0))} organisations, {n(hs.get('ai_system', 0))} AI systems, {n(hs.get('harmed_group', 0))} harmed groups, "
        f"{hs.get('risk_domain', 0)} risk domains, {hs.get('sector', 0)} sectors, plus generic actors and harm values). The entity co-occurrence network used for centrality and communities has "
        f"{n(f['entity_network_nodes'])} entities (those in at least {f['min_incidents']} incidents) and {n(f['entity_network_edges'])} links.\n"
        f"- **Most central organisations (PageRank):** {', '.join(f['top_org_pagerank'][:5])}; by weighted degree: {', '.join(f['top_org_weighted_degree'][:5])}. "
        f"The measures agree only moderately (Kendall tau between PageRank and weighted degree {f['tau_pagerank_vs_weighted_degree']:.2f}; lowest pair {f['tau_min_between_measures']:.2f}), so no single ranking should be quoted alone.\n"
        f"- **Communities:** {res.chosen_method.replace('_', ' ')} gives {f['n_communities']} communities (modularity {f['chosen_modularity']:.3f}; the largest holds {pct(largest_share, 0)} of entities). "
        f"{'Louvain and Leiden are statistically indistinguishable on modularity (difference within seed noise), ' if res.near_tie else ''}"
        f"label propagation fails on this hub-heavy network (modularity {lpa['modularity_mean']:.3f}, {pct(lpa['largest_share_mean'], 0)} of nodes in one community). "
        f"Stability across {cfg['n_seeds']} seeds is moderate (mean ARI {ch['stability_ari_mean']:.2f}, minimum {ch['stability_ari_min']:.2f}), so I report the most representative run (seed {res.medoid_seed}).\n"
        f"- **Communities versus risk domains:** normalised mutual information {f['nmi_community_vs_domain']:.2f}: communities detected from entity ties alone are "
        + ("only weakly" if f["nmi_community_vs_domain"] < 0.2 else "partly")
        + " aligned with MIT risk domains.\n"
        f"- **Robustness:** removing the {rob['n_hubs']} hub entities present in more than {pct(cfg['hub_share_cap'], 0)} of incidents gives modularity {rob['modularity_mean']:.3f} "
        f"and a partition that agrees with the main one at mean ARI {rob['ari_vs_main_mean']:.2f}"
        + (
            ": **community boundaries depend heavily on the generic hubs**, so the communities below are one reading of a hub-dominated network, not stable structure.\n"
            if rob["ari_vs_main_mean"] < 0.5
            else ": the community structure is robust to removing the generic hubs.\n"
        )
        + f"- **Over time:** the median overlap between consecutive years' top-10 organisations is {pct(f['median_top10_jaccard'], 0)} (Jaccard).\n"
    )
    add("## 1. Method\n")
    add(
        "- **Heterogeneous graph.** Incident nodes are linked to entity nodes by the role the entity plays (alleged deployer, alleged developer, harmed party, implicated system; "
        "an entity with several roles in one incident gets one link with combined role), to one MIT risk-domain node, and to CSETv1 sector nodes. "
        f"Node types come from the Phase 2 `entity_type`: organisation, AI system (`technology_system`), harmed group (`population_group`); generic actors and abstract harm values are kept as their own types "
        f"so that they never pose as organisations or groups.\n"
        f"- **Exclusions.** Person-like entities (`individual_candidate`; {n(f['excluded_person_like_mentions'])} entity mentions) are left out: RQ2 concerns organisations, systems and groups, "
        "and unreviewed named individuals do not belong in a network. Every named person (rule D3, `data/manual/entity_review.csv`) is already removed in Phase 2.\n"
        f"- **Entity co-occurrence network.** Two entities are linked with weight = number of incidents they share (the one-mode projection). Entities in fewer than {f['min_incidents']} incidents are dropped "
        "(they would be leaves hanging off other entities). Centrality and communities use this network; risk-domain and sector nodes are **not** part of community detection, so profiling communities by domain is not circular.\n"
        "- **Centrality.** Degree (distinct co-occurring entities), weighted degree (total shared incidents), exact betweenness (igraph; link length = 1 / weight, so strong ties are short; exact, so no sampling needed), "
        "PageRank (damping 0.85) and eigenvector centrality (largest connected component). Agreement between measures: Kendall's tau.\n"
        f"- **Communities.** Louvain (networkx), Leiden (leidenalg, modularity) and asynchronous label propagation, each with {cfg['n_seeds']} seeds. Modularity is computed identically for all. "
        f"Rule fixed in advance: the highest mean modularity among methods whose mean pairwise adjusted Rand index (ARI) across seeds is at least {cfg['min_stability_ari']}.\n"
        "- **Temporal evolution.** Cumulative snapshots at the end of each year (all entities, incidents up to that year): node and link growth by type, organisations first appearing in the year, "
        "and the top-10 organisations by PageRank in each cumulative network.\n"
    )
    add("## 2. Network size\n")
    add(
        to_markdown(
            pd.DataFrame({"node type": list(hs), "nodes": list(hs.values())}).sort_values(
                "nodes", ascending=False
            )
        )
    )
    add(
        f"\nSectors exist only for the {f['sector_coverage_incidents']} incidents CSETv1 annotated, so sector findings are thin by construction.\n"
    )
    add("## 3. Centrality\n")
    add("### Agreement between measures (all entities)\n")
    add(to_markdown(res.tau_all.round(2), index=True))
    add("")
    add(_figure("fig_rq2_3_centrality_tau", "Kendall's tau between centrality measures", snap))
    add(
        f"Organisations only: PageRank vs weighted degree tau = {res.tau_orgs.loc['pagerank', 'weighted_degree']:.2f}, betweenness vs eigenvector tau = {res.tau_orgs.loc['betweenness', 'eigenvector']:.2f}. "
        "Betweenness picks out *bridging* entities (for example generic hubs such as the general public, or large language models) rather than the most frequently mentioned ones; eigenvector centrality is dominated by the dense deepfake cluster.\n"
    )
    for measure, by_type in res.tops.items():
        add(f"### Top 10 by {measure.replace('_', ' ')}\n")
        for node_type, table in by_type.items():
            add(
                f"**{_TYPE_NAME[node_type].capitalize()}**"
                + (" (alleged deployers/developers)" if node_type == "organisation" else "")
                + "\n"
            )
            add(to_markdown(_centrality_view(table)))
            add("")
    add(_figure("fig_rq2_2_top_central", "Top 10 by PageRank per node type", snap))
    add("### Organisation x harmed-group projection (top 15 links)\n")
    add(
        "Weight = incidents in which the organisation is an alleged deployer or developer and the group is a harmed party.\n"
    )
    add(
        to_markdown(
            res.projection.head(15)[["left", "right", "weight"]].rename(
                columns={"left": "organisation (alleged)", "right": "harmed group"}
            )
        )
    )
    add("")
    add("## 4. Communities\n")
    add(to_markdown(res.method_summary.round(3)))
    add("")
    add(_figure("fig_rq2_4_community_methods", "Community detection methods compared", snap))
    add(
        f"**Rule outcome:** {res.chosen_method.replace('_', ' ')} ({res.chosen_reason}). "
        + (
            f"This is a near tie: {res.chosen_method.replace('_', ' ')} and {other.replace('_', ' ')} differ in mean modularity by less than one seed standard deviation, "
            f"and {other.replace('_', ' ')} is {'more' if ms.loc[other, 'stability_ari_mean'] > ch['stability_ari_mean'] else 'less'} stable (mean ARI {ms.loc[other, 'stability_ari_mean']:.2f} vs {ch['stability_ari_mean']:.2f}); "
            "either would support the same conclusions.\n"
            if res.near_tie
            else "\n"
        )
    )
    add(f"### Community profiles (most representative run, seed {res.medoid_seed})\n")
    add(
        "Incidents are assigned to the community that holds most of their entities. Domains and sectors describe those incidents; they were not used to form the communities. "
        "The domain mix is not shown for communities with fewer than 20 incidents, because it would reveal the labels of individual incidents.\n"
    )
    show = prof[
        [
            "community",
            "entities",
            "incidents",
            "organisations",
            "ai_systems",
            "harmed_groups",
            "domains",
            "sectors",
        ]
    ].copy()
    show["domains"] = show["domains"].str.slice(0, 120)
    add(to_markdown(show))
    add("")
    add(
        _figure(
            "fig_rq2_1_entity_network",
            "Entity co-occurrence network (top entities by weighted degree)",
            snap,
        )
    )
    add("### Robustness: removing hub entities\n")
    add(
        f"Entities appearing in more than {pct(cfg['hub_share_cap'], 0)} of incidents ({rob['limit_incidents']:.0f}+) are generic hubs that connect almost everything: "
        f"{', '.join(rob['hubs_removed'][:12])}{' ...' if rob['n_hubs'] > 12 else ''} ({rob['n_hubs']} entities). Re-running {res.chosen_method.replace('_', ' ')} without them gives modularity "
        f"{rob['modularity_mean']:.3f} on {n(rob['nodes_after'])} entities and agrees with the main partition at mean ARI {rob['ari_vs_main_mean']:.2f} (minimum {rob['ari_vs_main_min']:.2f}).\n"
    )
    add("## 5. Temporal evolution\n")
    add(
        to_markdown(res.snapshots[["year", "nodes", "edges", "new_organisations", "organisations"]])
    )
    add("")
    add(_figure("fig_rq2_5_network_growth", "Network growth and new organisations per year", snap))
    add(
        f"Years to {f['last_complete_year']} are complete; {f['partial_year']} is partial. New organisations per year largely follow incident volume, so growth in the network is mostly growth in coverage, not in structure.\n"
    )
    add("### Top-10 organisations by PageRank over time\n")
    pivot = res.top_orgs.pivot_table(
        index="organisation", columns="year", values="rank", aggfunc="first"
    )
    pivot = (
        pivot.loc[pivot.notna().sum(axis=1).sort_values(ascending=False).index]
        .fillna(0)
        .astype(int)
        .replace(0, "")
    )
    add(to_markdown(pivot.head(25), index=True))
    add("")
    add(to_markdown(res.overlap.round(2)))
    add("")
    add(
        _figure(
            "fig_rq2_6_top_organisations_over_time",
            "Rank of organisations in the yearly top 10 by PageRank",
            snap,
        )
    )
    add("## 6. Dashboard export\n")
    e = f["export"]
    add(
        f"`reports/network_graph.json`: {e['nodes']} nodes and {e['edges']} edges (top {cfg['export']['top_n']} entities by weighted degree, at most {cfg['export']['max_edges']} strongest links; {e['bytes'] / 1e3:.0f} kB). "
        "Each link carries per-year counts and each node its first and last year, so a year slider can show the cumulative network by summing counts up to the chosen year. "
        "Nodes carry a profile (risk-domain mix, up to five recent incidents) for the click panel, and the file states the *alleged involvement* caveat.\n"
    )
    add("## 7. Limitations\n")
    add(
        "- **Alleged involvement, not responsibility.** AIID records alleged developers and deployers; a central organisation is one named often, which also reflects what the media cover and what editors record.\n"
        "- **Entity types are heuristic** (Phase 2). Class-level groups such as law enforcement are typed as organisations; some generic entities are hubs. Treat type-specific rankings as indicative.\n"
        "- **Hubs and projection.** Projecting incidents onto entities turns every incident into a clique, so incidents naming many entities (up to dozens) inflate degrees and create dense blocks; weighted measures and the hub-removal check mitigate but do not remove this.\n"
        "- **Modularity limits.** Modularity has a resolution limit and the partitions are only moderately stable across seeds; communities are descriptive groupings, not natural kinds.\n"
        f"- **Coverage.** Sector nodes exist for {f['sector_coverage_incidents']} incidents; risk-domain nodes only for MIT-labelled incidents (machine-generated labels).\n"
        "- **Cumulative snapshots use the harm date**; late additions of old incidents change early years' networks retrospectively.\n"
        "- **Person-like entities were excluded**, which removes public figures who are frequent deepfake targets from the harmed-group picture; this is deliberate, pending your entity review.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    logger.info("Wrote %s", path)
