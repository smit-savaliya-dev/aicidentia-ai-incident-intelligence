"""Build docs/rq4_similarity.md from the Phase 7 results (titles only; no MIT labels are shown)."""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from aicidentia.config import load_config
from aicidentia.data.audit_docs import n, pct
from aicidentia.models import retrieval as R
from aicidentia.models.retrieval_outputs import BASELINE, SETTINGS, RetrievalResults
from aicidentia.viz.style import to_markdown

logger = logging.getLogger(__name__)


def _figure(name: str, caption: str, snapshot: str) -> str:
    return f"![{caption}](../reports/figures/{name}.png)\n\n*Figure: {caption}. Source: AIID snapshot {snapshot}.*\n"


def _ci(t: pd.Series, m: str) -> str:
    return f"{t[m]:.3f} [{t[f'{m}_low']:.3f}, {t[f'{m}_high']:.3f}]"


def _summary_table(summary: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, t in summary.iterrows():
        rows.append(
            {
                "method": R.LABELS[t["method"]],
                "queries": int(t["queries"]),
                "MRR [95% CI]": _ci(t, "rr"),
                "nDCG@10 [95% CI]": _ci(t, "ndcg@10"),
                "P@5": round(t["p@5"], 3),
                "Hit@5": pct(t["hit@5"]),
                "Recall@10": round(t["r@10"], 3),
                "dissimilar in top 5": ""
                if pd.isna(t.get("dissimilar@5"))
                else f"{t['dissimilar@5']:.3f}",
            }
        )
    return pd.DataFrame(rows)


def _comparison_table(comp: pd.DataFrame) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "method vs BM25": [R.LABELS[m] for m in comp["method"]],
            "MRR difference [95% CI]": [
                f"{d:+.3f} [{lo:+.3f}, {hi:+.3f}]"
                for d, lo, hi in zip(comp["diff"], comp["ci_low"], comp["ci_high"], strict=True)
            ],
            "p (paired bootstrap)": comp["p_value"].round(4),
            "p (Wilcoxon)": comp["wilcoxon_p"].round(4),
            "p (Wilcoxon, Holm)": comp["p_holm"].round(4),
            "queries better / worse / tied": [
                f"{b} / {w} / {t}"
                for b, w, t in zip(comp["better"], comp["worse"], comp["ties"], strict=True)
            ],
        }
    )


def write_retrieval_doc(res: RetrievalResults, path: Path) -> None:
    """Write docs/rq4_similarity.md."""
    cfg = load_config()
    snap = str(cfg["snapshot_date"])
    f = res.facts
    s = res.summary["all"].set_index("method")
    comp = res.comparisons["all"].set_index("method")
    best = f["best_method"]
    ov = f["aiid_suggestion_overlap"]
    lex_best = max(R.LEXICAL, key=lambda m: s.loc[m, "rr"])
    emb_best = max(("minilm", "mpnet"), key=lambda m: s.loc[m, "rr"])
    order_all = list(s["rr"].sort_values(ascending=False).index)
    order_earlier = list(
        res.summary["earlier"].set_index("method")["rr"].sort_values(ascending=False).index
    )

    L: list[str] = []
    add = L.append
    add("# RQ4: similar-incident retrieval (Phase 7)\n")
    add(
        f"_Auto-generated by `aicidentia.models.retrieval_outputs` (AIID snapshot **{snap}**). Numbers are registered in `reports/results.json` under `rq4.*`._\n"
    )
    add("## Summary\n")
    best_row = comp.loc[best] if best != BASELINE else None
    add(
        f"- **Ground truth:** AIID editors' own *similar incident* links in the snapshot, **no manual judgements were needed**. {n(f['queries'])} incidents have at least one editor-marked similar incident in the analysis set "
        f"({n(f['relevant_pairs'])} distinct pairs; {pct(f['oracle']['queries_with_one_relevant'])} of queries have exactly one). Editor-marked *dissimilar* links ({f['dissimilar_queries']} queries) serve as hard negatives.\n"
        f"- **Ranking by MRR:** {' > '.join(R.LABELS[m] for m in order_all)}. Best: **{R.LABELS[best]}**, MRR {_ci(s.loc[best], 'rr')}; BM25 {_ci(s.loc['bm25'], 'rr')}.\n"
        + (
            f"- **Is the best method really better than BM25?** Primary test (paired bootstrap of the mean MRR difference): {best_row['diff']:+.3f}, 95% CI [{best_row['ci_low']:+.3f}, {best_row['ci_high']:+.3f}], "
            f"{'not significant' if best_row['ci_low'] <= 0 <= best_row['ci_high'] else 'significant'}. "
            f"The Wilcoxon signed-rank test, which looks at how often a query improves rather than by how much, {'agrees' if (best_row['p_holm'] < 0.05) == (not (best_row['ci_low'] <= 0 <= best_row['ci_high'])) else 'disagrees'} "
            f"(Holm-adjusted p = {best_row['p_holm']:.4f}; better on {int(best_row['better'])} queries, worse on {int(best_row['worse'])}, tied on {int(best_row['ties'])}).\n"
            if best_row is not None
            else ""
        )
        + f"- **Lexical vs semantic:** the best lexical method ({R.LABELS[lex_best]}, MRR {s.loc[lex_best, 'rr']:.3f}) scores higher than the best embedding model ({R.LABELS[emb_best]}, {s.loc[emb_best, 'rr']:.3f}); "
        + "; ".join(
            f"{R.LABELS[m]} vs BM25 {comp.loc[m, 'diff']:+.3f} [{comp.loc[m, 'ci_low']:+.3f}, {comp.loc[m, 'ci_high']:+.3f}] ({'significant' if not (comp.loc[m, 'ci_low'] <= 0 <= comp.loc[m, 'ci_high']) else 'not significant'})"
            for m in ("minilm", "mpnet")
        )
        + ". A plausible explanation (not tested here) is that editor-linked incidents often share specific names of systems, companies or places, which exact-term matching rewards; the hybrid combines both signals.\n"
        f"- **Precedent search** (only earlier incidents as candidates, {n(f['queries_earlier'])} queries): same picture, ranking {' > '.join(R.LABELS[m] for m in order_earlier)}.\n"
        f"- **Deployed in the dashboard: {R.LABELS[f['deployed']]}.** {f['deployed_reason'][0].upper() + f['deployed_reason'][1:]}. The other methods remain selectable.\n"
        f"- **AIID's own stored suggestions** (top 3 per incident) contain only {pct(ov['share_in_aiid_suggestions'])} of the editor links and reach MRR@3 = {f['aiid_nlp_rr3']:.3f}, "
        f"against {s.loc[best, 'rr@3']:.3f} for {R.LABELS[best]}. So the editor links were not simply copied from those suggestions (which limits one source of bias in the ground truth).\n"
    )
    add("## 1. Ground truth\n")
    add(
        f"- **Source:** `editor_similar_incidents` in the MongoDB snapshot (Phase 1 audit). A link A -> B is treated as relevant in both directions (symmetrised); links to incidents outside the {n(f['indexed_incidents'])}-incident analysis set and self-links are dropped.\n"
        f"- **Queries:** the {n(f['queries'])} incidents with at least one relevant incident; mean {f['relevant_per_query_mean']:.2f} relevant per query.\n"
        f"- **Ceilings:** because most queries have a single relevant incident, the best achievable mean Precision@5 is {f['oracle']['p@5']:.3f} (and P@3 {f['oracle']['p@3']:.3f}). "
        "MRR and nDCG@10 are therefore the informative metrics; P@5 is reported because the research question names it.\n"
        "- **Incompleteness:** editors mark similar incidents when they notice them; an unmarked incident is not necessarily dissimilar. All methods are penalised equally for finding unmarked but genuinely similar incidents, so the comparison is fair, but absolute scores are lower bounds.\n"
        "- **Hard negatives:** `editor_dissimilar_incidents` (symmetrised). 'Dissimilar in top 5' is the share of the top 5 that editors explicitly marked as *not* similar (lower is better).\n"
    )
    add("## 2. Methods and protocol\n")
    add(
        "Each incident is represented by its title + description (`text`), the same input as Phases 3 and 6. Fixed in advance; nothing was tuned on the ground truth:\n\n"
        "- **TF-IDF:** word 1-2-grams, sublinear tf, English stopwords, min_df 2, cosine similarity.\n"
        f"- **BM25:** Okapi BM25 (k1 = {R.BM25_K1}, b = {R.BM25_B}; `rank-bm25`) on the project's shared tokenisation (lemmatised, standard and domain stopwords removed).\n"
        "- **MiniLM / mpnet:** cosine similarity of L2-normalised sentence embeddings (all-MiniLM-L6-v2, all-mpnet-base-v2; the same cached vectors as Phase 6).\n"
        f"- **Hybrid:** reciprocal rank fusion of the BM25 and mpnet rankings with k = {R.RRF_K} (the standard constant).\n\n"
        "For each query every other incident is ranked; ties are broken by incident id. Metrics: MRR (reciprocal rank of the first relevant incident over the full ranking; primary), nDCG@10 (binary gains), Precision@5, Hit@5, Recall@k. "
        f"Means carry percentile bootstrap 95% CIs over queries ({cfg['retrieval']['n_boot']} resamples). Each method is compared with BM25 on the same queries by a paired bootstrap of the mean MRR difference (primary) and the Wilcoxon signed-rank test with Holm correction across the four comparisons.\n"
    )
    add("## 3. Results\n")
    for setting, text in SETTINGS.items():
        add(f"### Setting: {text}\n")
        add(to_markdown(_summary_table(res.summary[setting])))
        add("")
        add(to_markdown(_comparison_table(res.comparisons[setting])))
        add("")
    add(
        _figure(
            "fig_rq4_1_method_comparison",
            "MRR, nDCG@10 and Precision@5 per method with bootstrap 95% CIs",
            snap,
        )
    )
    add(_figure("fig_rq4_2_recall_at_k", "Recall@k per method", snap))
    add("### AIID's stored suggestions as a reference\n")
    add(
        f"The snapshot stores three NLP-based suggestions per incident (`nlp_similar_incidents`). Scored at depth 3 they reach MRR@3 = {f['aiid_nlp_rr3']:.3f}. "
        "Their provenance (model, input text, and when they were computed) is not documented in the snapshot; if they were computed when each incident was created, later incidents could not appear in them, "
        "which alone would depress their scores. They are shown for context, not as a competing method.\n"
    )
    add(to_markdown(res.suggestions.round(3)))
    add("")
    add("## 4. Examples (deployed method, titles only)\n")
    add(
        "Two queries where an editor-similar incident appears in the top 5 and one where it does not (chosen by seed). Checked rows are editor-marked similar.\n"
    )
    for q, sub in res.examples.groupby("query", sort=False):
        add(
            f"**Query #{q}: {sub['query_title'].iloc[0]}** (first editor-similar incident at rank {int(sub['first_relevant_rank'].iloc[0])})\n"
        )
        add(
            to_markdown(
                sub.assign(similar=sub["editor_similar"].map({True: "yes", False: ""}))[
                    ["rank", "incident_id", "title", "similar"]
                ]
            )
        )
        add("")
    rp = res.repeat
    if rp:
        f3 = res.facts["mrr3"]
        dep = rp["found_in_top5"][res.deployed]
        add("## 5. Repeated failures: does a precedent exist, and do we find it?\n")
        add(
            f"Of the {rp['recent_incidents']:,} incidents from {rp['from_year']} on, **{rp['recent_with_earlier_precedent']} ({100 * rp['share_with_earlier_precedent']:.1f}%) have an editor-linked earlier precedent** "
            f"({rp['recent_with_any_editor_link']} have any editor link). Searching only incidents that happened before each of them, the deployed method ({R.LABELS[res.deployed]}) puts a precedent in its top 5 "
            f"for **{100 * dep['hit@5']:.0f}%** (95% CI {100 * dep['ci_low']:.0f}-{100 * dep['ci_high']:.0f}%). "
            "The share with a precedent is a lower bound: editors link only some incidents, and recent ones may not yet be linked.\n"
        )
        rows = pd.DataFrame(
            [
                {
                    "method": R.LABELS[m],
                    "found in top 5": f"{100 * v['hit@5']:.0f}% [{100 * v['ci_low']:.0f}, {100 * v['ci_high']:.0f}]",
                    "MRR@3": round(v["mrr3"], 3),
                }
                for m, v in rp["found_in_top5"].items()
            ]
        )
        add(to_markdown(rows))
        add("")
        add(
            f"**Like-for-like with AIID's built-in suggestions (MRR@3, all {res.facts['queries']} queries, all incidents as candidates):** "
            + ", ".join(f"{R.LABELS[m]} {v:.3f}" for m, v in f3.items())
            + f"; AIID's own suggestions {res.facts['aiid_nlp_rr3']:.3f}. AIID offers only three suggestions, so depth 3 is the fair comparison; the provenance caveat in section 3 still applies.\n"
        )
    add("## 6. Limitations\n")
    add(
        "- **Sparse, incomplete ground truth:** most queries have one relevant incident and editors do not mark every similar pair, so scores are lower bounds and small differences between methods are hard to detect.\n"
        "- **Query selection:** only incidents with editor links are evaluated; they are mostly recent (2023-2026), when editors used the feature most, so results describe recent incidents best.\n"
        "- **What 'similar' means to editors** (same system, same company, same kind of harm, a follow-up event) is not recorded; methods that match names are rewarded when editors link incidents about the same product.\n"
        "- **Short texts:** only title + description are indexed; full report text might change the ranking (not tested, to keep the input identical across phases).\n"
        "- **The hybrid's gain is small** and depends on the test used (see section 3); it is not deployed because the pre-specified rule requires a significant paired-bootstrap improvement.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    logger.info("Wrote %s", path)
