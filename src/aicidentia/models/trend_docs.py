"""Build docs/rq1_trends.md from the Phase 4 results."""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from aicidentia.config import load_config
from aicidentia.data.audit_docs import n, pct
from aicidentia.models.trend_outputs import JUSTIFIED_IMPROVEMENT, TrendResults
from aicidentia.viz.style import to_markdown

logger = logging.getLogger(__name__)


def _figure(name: str, caption: str, snapshot: str) -> str:
    return f"![{caption}](../reports/figures/{name}.png)\n\n*Figure: {caption}. Source: AIID snapshot {snapshot}.*\n"


def _trend_display(table: pd.DataFrame, scale: float = 100.0, unit: str = "pp/yr") -> pd.DataFrame:
    """Readable trend table: slope in percentage points per year with its 95% interval."""
    out = pd.DataFrame(
        {
            "group": table["group"],
            "tau": table["tau"].round(2),
            f"Sen slope ({unit})": (table["sen_slope"] * scale).round(2),
            "95% CI": [
                f"[{lo * scale:.2f}, {hi * scale:.2f}]"
                for lo, hi in zip(table["slope_low"], table["slope_high"], strict=True)
            ],
            "p": table["p"].round(4),
            "p (BH)": table["p_bh"].round(4),
            "p (Hamed-Rao)": table["p_hamed_rao"].round(4),
            "long-run mean (%)": (table["longrun_mean"] * scale).round(1),
            "recent mean (%)": (table["recent_mean"] * scale).round(1),
            "direction": table["direction"],
            "emerging": table["emerging"].map({True: "YES", False: ""}),
        }
    )
    return out


def write_trend_doc(res: TrendResults, path: Path) -> None:
    """Write docs/rq1_trends.md."""
    cfg = load_config()["trends"]
    snap = str(load_config()["snapshot_date"])
    f, info = res.facts, res.info
    years = res.years
    themes_sh = res.tests["themes"]["share"]
    domains_sh = res.tests["domains"]["share"]
    cls = res.classification["themes"]
    cls_d = res.classification["domains"]
    reports = res.tables["reports_by_year"]
    first_r, last_r = reports.iloc[0], reports[reports["year"] == years[-1]].iloc[0]
    emerging = f["emerging_themes"]
    decreasing = themes_sh.loc[themes_sh["direction"] == "decreasing", "group"].tolist()
    disagree = f["themes_with_disagreeing_bases"]
    summary = res.forecast_summary.set_index("model")
    prov = f["provisional"]

    L: list[str] = []
    add = L.append
    add("# RQ1b: trends over time (Phase 4)\n")
    if prov:
        add(
            f"> **PROVISIONAL.** Only {info['n_answered']} of {info['n_topics']} topic labels in `data/manual/topic_labels.csv` are confirmed, so themes carry the automatic placeholder names "
            "`T<id>: <first terms>`. The statistics depend only on which topic each incident belongs to, so they will not change when you add names; they **will** change if you merge topics "
            "(give two topics the same `final_label`) or if the topic model is re-fitted. Re-run `scripts/run_phase4_trends.py` after labelling.\n"
        )
    elif info["merged_themes"]:
        add(f"_Topic labels confirmed; merged themes: {info['merged_themes']}._\n")
    add(
        f"_Auto-generated by `aicidentia.models.trend_outputs` (AIID snapshot **{snap}**). Numbers are registered in `reports/results.json` under `rq1b.*`._\n"
    )
    add("## Summary\n")
    add(
        f"- **Window:** complete years {years[0]}-{years[-1]} ({len(years)} annual points; the partial year {f['partial_year']}, {n(f['partial_year_incidents'])} incidents, is shown but never tested). "
        f"Sensitivity window {res.late_years[0]}-{res.late_years[-1]}.\n"
        f"- **Emerging themes (primary measure: yearly share, BH-adjusted):** "
        + (", ".join(f"**{t}**" for t in emerging) if emerging else "none")
        + f". Significantly declining: {', '.join(decreasing) if decreasing else 'none'}.\n"
        f"- **Counts overstate growth.** On raw counts {f['increasing_counts']} of {f['n_themes']} themes are 'increasing'; on shares {f['increasing_share']}; "
        f"on report-weighted shares {f['increasing_wshare']}. Yearly incident counts rise steeply across the window, so a count-based test mostly detects database growth.\n"
        f"- **{f['n_themes_disagree']} of {f['n_themes']} themes change classification depending on the measure** (counts vs share vs report-weighted share: the reporting-bias comparison; see section 3). "
        f"A further {f['n_themes_window_sensitive']} themes change when the window is shortened to {res.late_years[0]}-{res.late_years[-1]}, which mostly reflects lower power with {len(res.late_years)} years.\n"
        f"- **MIT risk domains** (shares among MIT-labelled incidents): "
        + (
            f"emerging: {', '.join(f['domains_emerging'])}"
            if f["domains_emerging"]
            else "no domain meets the 'emerging' definition"
        )
        + ".\n"
        f"- **Forecasting is {'justified' if f['forecast_justified'] else 'NOT justified'} on this evidence:** best model {f['forecast_best_model']} has mean MASE {f['forecast_best_mase']:.2f} "
        f"vs {f['forecast_naive_mase']:.2f} for the naive forecast (threshold for 'justified': at most {pct(JUSTIFIED_IMPROVEMENT, 0)} of naive).\n"
        + (
            "- **OECD AIM replication:** not performed; `data/external/` is empty.\n"
            if not f["oecd_aim_files"]
            else f"- **OECD AIM:** files found ({', '.join(f['oecd_aim_files'])}) but replication is not implemented for them; ask before relying on it.\n"
        )
    )
    add("## 1. Method\n")
    add(
        f"- **Series.** For each theme and year: *count*; *share* = incidents of the theme / all incidents of that year; *report-weighted share* = reports on the theme's incidents / reports on all incidents "
        "(each incident weighted by its number of non-stub linked reports, a proxy for media attention). For MIT risk domains the denominator is MIT-labelled incidents only.\n"
        "- **Test.** Mann-Kendall (pymannkendall `original_test`) with Sen's slope; Kendall's tau; a Theil-Sen 95% interval for the slope (scipy); the Hamed-Rao autocorrelation-corrected p-value as a robustness column.\n"
        f"- **Multiple testing.** Benjamini-Hochberg at q = {cfg['alpha']} within each family (themes on one measure; domains on one measure). A series is *increasing*/*decreasing* if its BH-adjusted p is below q.\n"
        f"- **Emerging** = increasing (BH-significant, positive Sen slope) **and** the mean share of the last {cfg['recent_years']} complete years ({years[-cfg['recent_years']]}-{years[-1]}) above the long-run mean share over the window.\n"
        "- **Slopes** are in percentage points of share per year (pp/yr).\n"
        f"- **Themes** come from the Phase 3 model (`{info['model_key']}`), every incident assigned to its dominant topic; the topic model was fitted on all incidents, not only the test window.\n"
    )
    add("## 2. Results: themes (primary measure = yearly share)\n")
    add(to_markdown(_trend_display(themes_sh)))
    add("")
    add(
        _figure(
            "fig_rq1b_1_theme_heatmap",
            "Theme share by year, ordered by Sen slope (* = partial year, shown faded and never tested)",
            snap,
        )
    )
    add(_figure("fig_rq1b_2_emerging_themes", "Themes meeting the emerging definition", snap))
    add("## 3. Reporting-bias sensitivity: do conclusions depend on how we measure?\n")
    add(
        "Each theme is classified under four measures. Raw counts mix real change with AIID's collection effort; shares remove overall growth; report-weighted shares add media attention. "
        "`agree` compares these first three (the reporting-bias question); "
        f"`window_sensitive` flags themes whose share-based direction changes in the later window ({res.late_years[0]}-{res.late_years[-1]}), a start-year check with only {len(res.late_years)} points and therefore little power.\n"
    )
    show = cls.reset_index(names="theme")
    show["agree"] = show["agree"].map({True: "", False: "DISAGREE"})
    show["window_sensitive"] = show["window_sensitive"].map({True: "differs", False: ""})
    add(to_markdown(show))
    add("")
    add(
        _figure(
            "fig_rq1b_3_trend_by_measure",
            "Trend direction of every theme and MIT domain under each measure",
            snap,
        )
    )
    add("### Where the measures disagree\n")
    if disagree:
        add(
            f"{len(disagree)} theme(s) are classified differently across measures: "
            + "; ".join(f"**{t}**" for t in disagree)
            + ". "
            "For these, the substantive conclusion depends on whether growth in database volume or in media attention is treated as part of the phenomenon; "
            "the share-based result is the primary one because it removes overall growth.\n"
        )
    else:
        add("All themes receive the same classification under every measure.\n")
    add("### Reports per incident by incident year (why report-weighting is itself biased)\n")
    add(to_markdown(reports.round(2)))
    add("")
    if last_r["mean_reports"] < first_r["mean_reports"]:
        add(
            f"Incidents from {int(last_r['year'])} have on average {last_r['mean_reports']:.2f} linked reports against {first_r['mean_reports']:.2f} for {int(first_r['year'])}. "
            "Recent incidents have had less time to attract coverage, so **report-weighted shares understate recent themes**; the weighting measures attention accumulated so far, not attention at the time. "
            "Use it only as a sensitivity check.\n"
        )
    else:
        add(
            f"Mean reports per incident do not fall for recent years ({last_r['mean_reports']:.2f} in {int(last_r['year'])} vs {first_r['mean_reports']:.2f} in {int(first_r['year'])}).\n"
        )
    add("## 4. Results: MIT risk domains (shares among MIT-labelled incidents)\n")
    cover = res.tables["mit_coverage"]
    add(
        f"MIT labels are missing for some incidents, increasingly so for recent ones (labelled share: {pct(cover.iloc[len(years) - 1]['mit_labelled_share'])} in {years[-1]}, "
        f"{pct(cover.iloc[-1]['mit_labelled_share'])} in the partial {f['partial_year']}); shares use labelled incidents as the denominator, so a trend can partly reflect *which* incidents received a label.\n"
    )
    add(to_markdown(_trend_display(domains_sh)))
    add("")
    add("Direction under each measure:\n")
    add(
        to_markdown(
            cls_d.reset_index(names="domain").assign(
                agree=lambda d: d["agree"].map({True: "", False: "DISAGREE"})
            )
        )
    )
    add("")
    add("## 5. Forecasting quarterly counts\n")
    add(
        f"Quarterly counts {years[0]}Q1-{years[-1]}Q4 ({4 * len(years)} quarters) for the total and every theme; rolling origin from {cfg['forecast']['initial_quarters']} quarters, horizon 1-{cfg['forecast']['horizon']} quarters. "
        "Models: naive (last value), exponential smoothing (better by AICc of simple and damped-trend ETS), ARIMA (order chosen by AICc from a small grid). "
        "Metric: MASE, scaled by the in-sample one-step naive error, averaged over origins, horizons and series. No forecast beyond the last complete quarter is produced.\n"
    )
    add(to_markdown(res.forecast_summary.round(3)))
    add("")
    skipped = res.forecast_skipped
    if len(skipped):
        add(
            "Not scored: "
            + "; ".join(f"{r.series} ({r.reason})" for r in skipped.itertuples())
            + ".\n"
        )
    best_alt = summary.drop(index="naive")["mean_mase_all_horizons"].min()
    add(
        f"**Reading:** every model has mean MASE above 1 (best: {best_alt:.2f}), because the series grow faster than any of these models extrapolate and the training-window naive error that scales MASE is small. "
        f"The best non-naive model reaches {pct(best_alt / summary.loc['naive', 'mean_mase_all_horizons'], 0)} of the naive error, against the {pct(JUSTIFIED_IMPROVEMENT, 0)} threshold set for 'justified'. "
        + (
            f"**Forecasting is not justified**: with {4 * len(years)} quarters of strongly growing, small counts, a naive forecast is as good as the fitted models, and publishing forecasts would imply accuracy that was not demonstrated.\n"
            if not f["forecast_justified"]
            else "Forecasting is justified for aggregate counts; per-theme forecasts should still be treated with caution.\n"
        )
    )
    add(
        _figure(
            "fig_rq1b_4_forecast_mase",
            "Rolling-origin forecast error (MASE) by model and horizon",
            snap,
        )
    )
    add("## 6. External replication (OECD AIM)\n")
    add(
        "Not performed: no OECD AIM export is present in `data/external/`. If you add one, tell me its format and I will check whether the AIID trends replicate.\n"
        if not f["oecd_aim_files"]
        else f"Files present: {', '.join(f['oecd_aim_files'])}.\n"
    )
    add("## 7. Limitations\n")
    add(
        f"- **Short series.** {len(years)} annual points give the Mann-Kendall test little power: only strong monotone trends are detected, and a non-significant result is not evidence of stability. "
        "Benjamini-Hochberg across a dozen themes lowers power further.\n"
        "- **Reporting bias is the main caveat.** AIID records incidents that were reported and editorially accepted; a rising share of a theme can reflect editorial focus, new submission channels or news cycles, not more harm.\n"
        "- **Theme definitions are recent-weighted.** The topic model was fitted on all incidents, most of which are recent, so themes describe recent incidents best; older incidents are assigned to the nearest theme even if their real subject differs.\n"
        "- **Hard assignment and shares.** Each incident has one dominant theme, and many sit between themes (Phase 3), so shares are shares of *dominant* assignment.\n"
        "- **Shares are compositional.** If one theme grows, the others must shrink in share; a declining share does not mean fewer incidents (see the counts column in the classification table).\n"
        "- **Label coverage.** MIT-domain trends use labelled incidents only, and coverage falls for recent years.\n"
        "- **No causal interpretation.** Trends describe the database, not the prevalence of AI harm.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    logger.info("Wrote %s", path)
