"""Build docs/rq3_classification.md from the Phase 6 results."""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import pandas as pd

from aicidentia.config import load_config
from aicidentia.data.audit_docs import n, pct
from aicidentia.models.classify_outputs import (
    ABLATION,
    BASELINE,
    DISTIL,
    DUMMY,
    ClassificationResults,
)
from aicidentia.viz.style import to_markdown

logger = logging.getLogger(__name__)


def _figure(name: str, caption: str, snapshot: str) -> str:
    return f"![{caption}](../reports/figures/{name}.png)\n\n*Figure: {caption}. Source: AIID snapshot {snapshot}.*\n"


def _ci(row: pd.Series) -> str:
    return f"{row['macro_f1']:.3f} [{row['ci_low']:.3f}, {row['ci_high']:.3f}]"


def write_classification_doc(res: ClassificationResults, path: Path) -> None:
    """Write docs/rq3_classification.md."""
    cfg = load_config()
    snap = str(cfg["snapshot_date"])
    d, f, m = res.data, res.facts, res.metrics
    cv = m[m["setting"] == "cv"].set_index("model")
    tm = m[m["setting"] == "time"].set_index("model")
    sig = res.significance
    best = res.best_model
    best_row = cv.loc[best]
    base = cv.loc[BASELINE]
    cal = res.calibration
    counts = pd.Series(f["class_counts"]).sort_values(ascending=False)
    local = [n_ for n_ in cv.index if n_ not in (DUMMY, DISTIL) and "ablation" not in n_]
    sig_cv = sig[
        (sig["setting"] == "cv") & (sig["model_b"] == BASELINE) & (sig["model_a"] != DUMMY)
    ]
    n_sig = int((sig_cv["p_value"] < 0.05).sum())
    spread = cv.loc[local, "macro_f1"]

    def row_for(table: pd.DataFrame, name: str) -> pd.Series:
        return table.loc[name]

    L: list[str] = []
    add = L.append
    add("# RQ3: risk-domain classification and label reliability (Phase 6)\n")
    add(
        f"_Auto-generated by `aicidentia.models.classify_outputs` (AIID snapshot **{snap}**). Numbers are registered in `reports/results.json` under `rq3.*`._\n"
    )
    add(
        "> **Read this first.** The target (MIT Risk Domain) is a *machine-generated* label. Classifier accuracy below measures how well the incident text reproduces that automatic labeller; it says nothing about agreement with human judgement. "
        "That second question is answered with independent signals already in AIID (section 5).\n"
    )
    add("## Summary\n")
    add(
        f"- **Data:** {n(f['labelled'])} MIT-labelled incidents, {len(d.classes)} classes (largest {pct(counts.iloc[0] / counts.sum())}, smallest {int(counts.iloc[-1])}); input is title + description. "
        f"A majority-class model scores macro-F1 {cv.loc[DUMMY, 'macro_f1']:.3f} (accuracy {pct(cv.loc[DUMMY, 'accuracy'])}).\n"
        f"- **Best cross-validated model: {best}**, macro-F1 {_ci(best_row)} (pooled out-of-fold, bootstrap 95% CI), accuracy {pct(best_row['accuracy'])}. "
        f"{BASELINE}: {_ci(base)}. The five local models span {spread.min():.3f} to {spread.max():.3f}; only {n_sig} of {len(sig_cv)} paired comparisons with {BASELINE} reach p < 0.05, so most differences between the real models are within noise.\n"
        + (
            f"- **DistilBERT (fine-tuned on the local GPU; Colab notebook as alternative):** macro-F1 {_ci(cv.loc[DISTIL])}; see section 2 for how it compares.\n"
            if res.colab_present
            else "- **DistilBERT:** *not yet run.* `notebooks/colab_distilbert_finetune.ipynb` is ready (same folds and seeds); copy its output to `reports/colab/rq3_distilbert_predictions.csv` and re-run `scripts/run_phase6_classification.py`.\n"
        )
        + f"- **Time split (train <= 2023, test >= 2024; {n(f['time_train'])} / {n(f['time_test'])} incidents):** the best model scores {_ci(tm.loc[best])} against {_ci(cv.loc[best])} in cross-validation "
        + (
            f"(lower by {cv.loc[best, 'macro_f1'] - tm.loc[best, 'macro_f1']:.3f}; this mixes distribution shift with a smaller training set, {n(f['time_train'])} incidents against about {n(round(f['labelled'] * 0.8))} per fold)"
            if tm.loc[best, "macro_f1"] < cv.loc[best, "macro_f1"] - 0.02
            else "(similar)"
        )
        + ".\n"
        f"- **Deployable model: {res.deployable}**, confidence method: {'none (uncalibrated probabilities)' if f['calibration_method'] == 'raw' else f['calibration_method']}. "
        f"Expected calibration error: uncalibrated {f['ece']['raw']:.3f}, Platt {f['ece']['sigmoid']:.3f}, temperature scaling {f['ece']['temperature']:.3f}. "
        f"Saved to `{f['model_path']}` (git-ignored); predictions for every incident are in `data/processed/rq3_domain_predictions.parquet`.\n"
    )
    if res.reliability is not None:
        rf = res.reliability.facts
        mk = res.reliability.mappings.set_index("mapping")
        ps = rf["pairs_similar"]
        add(
            "- **Label reliability (section 5), three independent checks:** "
            f"(a) against human CSETv1 fields the MIT discrimination label agrees substantially (kappa {mk.loc['discrimination_vs_protected_characteristic', 'kappa']:.2f}, n = {int(mk.loc['discrimination_vs_protected_characteristic', 'n'])}), "
            f"the safety label moderately (kappa {mk.loc['safety_vs_tangible_harm', 'kappa']:.2f}); "
            f"(b) {pct(ps['same_domain_rate'])} of editor-linked similar pairs share an MIT domain against {pct(ps['baseline_rate'])} for random same-year pairs; "
            f"(c) confident learning estimates that {pct(rf['cl_noise_rate'])} of labels are wrong and flags {n(rf['cl_flagged'])} incidents ({pct(rf['cl_flagged_share'])}).\n"
        )
    add("## 1. Method\n")
    add(
        f"- **Target and input.** MIT Risk Domain ({len(d.classes)} classes) as agreed in Phase 1 (docs/data_audit.md, D1); input = `text` (title + description).\n"
        f"- **Splits.** Stratified 5-fold cross-validation with folds fixed once (seed {cfg['random_seed']}, saved in `reports/colab/rq3_colab_input.csv` so the DistilBERT run uses identical folds), "
        f"and a time split (train before 2024: {n(f['time_train'])}; test from 2024: {n(f['time_test'])}). The time-split test set contains only labelled incidents.\n"
        "- **Models.** Majority class; TF-IDF (1-2-grams, min_df 2, sublinear) + logistic regression; TF-IDF + linear SVM; frozen sentence embeddings (all-MiniLM-L6-v2, all-mpnet-base-v2) + logistic regression; DistilBERT fine-tuned on the local GPU (same protocol as the Colab notebook). "
        '`class_weight="balanced"` everywhere it exists (DistilBERT uses the equivalent class-weighted loss).\n'
        "- **Tuning without leakage.** The regularisation strength is chosen by an inner 3-fold CV (macro-F1) inside each training part, so no test fold influences any choice (nested CV). DistilBERT's hyperparameters were fixed in advance.\n"
        f"- **Metrics.** Macro-F1 is primary (the classes are very unequal), with weighted-F1, accuracy and per-class precision/recall/F1. Confidence intervals are percentile bootstrap (resampling incidents, {cfg['classification']['n_boot']} draws) of the pooled out-of-fold predictions. "
        "Paired comparisons use the paired bootstrap of the macro-F1 difference and the exact McNemar test on correctness.\n"
        "- **Deployable-model rule (fixed in advance).** The local model with the best cross-validated macro-F1, unless its paired advantage over TF-IDF + LR is not significant, in which case TF-IDF + LR (no model download, works offline).\n"
    )
    add("## 2. Results\n")
    show = m[~m["model"].str.contains("ablation")].copy()
    show["macro-F1 [95% CI]"] = show.apply(_ci, axis=1)
    show["accuracy"] = show["accuracy"].map(pct)
    show["weighted-F1"] = show["weighted_f1"].round(3)
    show["per-fold macro-F1 (mean ± sd)"] = show.apply(
        lambda r: (
            ""
            if pd.isna(r.get("fold_macro_f1_mean"))
            else f"{r['fold_macro_f1_mean']:.3f} ± {r['fold_macro_f1_sd']:.3f}"
        ),
        axis=1,
    )
    add(
        to_markdown(
            show[
                [
                    "model",
                    "setting",
                    "n",
                    "macro-F1 [95% CI]",
                    "weighted-F1",
                    "accuracy",
                    "per-fold macro-F1 (mean ± sd)",
                ]
            ]
        )
    )
    add("")
    add(_figure("fig_rq3_1_model_comparison", "Macro-F1 by model with bootstrap 95% CI", snap))
    add("### Paired comparisons\n")
    add(
        "Difference in macro-F1 (model A minus model B) on identical incidents; p-values from the paired bootstrap and the exact McNemar test.\n"
    )
    s = sig.copy()
    s["difference [95% CI]"] = s.apply(
        lambda r: f"{r['diff']:+.3f} [{r['ci_low']:+.3f}, {r['ci_high']:+.3f}]", axis=1
    )
    s["p (bootstrap)"] = s["p_value"].round(4)
    s["p (McNemar)"] = s["mcnemar_p"].round(4)
    add(
        to_markdown(
            s[
                [
                    "model_a",
                    "model_b",
                    "setting",
                    "difference [95% CI]",
                    "p (bootstrap)",
                    "p (McNemar)",
                ]
            ]
        )
    )
    add("")
    if res.colab_present:
        dv = sig[(sig["model_a"] == DISTIL) & (sig["setting"] == "cv")]
        verdict = "does not beat" if (dv.iloc[0]["ci_low"] <= 0) else "beats"
        add(
            f"**DistilBERT vs {BASELINE}:** difference {dv.iloc[0]['diff']:+.3f} (95% CI [{dv.iloc[0]['ci_low']:+.3f}, {dv.iloc[0]['ci_high']:+.3f}]): the fine-tuned model {verdict} the baseline at the 5% level.\n"
        )
    else:
        add(
            "**DistilBERT:** pending (run `scripts/train_distilbert_local.py` or the Colab notebook); it will be scored in exactly this table with the same folds, and reported whether or not it beats the baseline.\n"
        )
    add("### Per-domain results (out-of-fold)\n")
    pc = res.per_class[
        res.per_class["class"].isin(d.classes)
        & ~res.per_class["model"].str.contains("ablation|majority")
    ]
    add(
        to_markdown(
            pc.pivot_table(index="class", columns="model", values="f1")
            .round(3)
            .reindex(counts.index),
            index=True,
        )
    )
    add("")
    add(_figure("fig_rq3_3_per_class_f1", "Per-domain F1 by model", snap))
    add(
        f"The two smallest domains ({', '.join(counts.index[-2:])}; {int(counts.iloc[-2])} and {int(counts.iloc[-1])} incidents) are far harder than the large ones, "
        "and with about five test cases of the smallest class per fold their scores are very uncertain; the pooled out-of-fold numbers use all of them but remain noisy.\n"
    )
    add("### Ablation: adding report text\n")
    ab = cv.loc[ABLATION.name]
    add(
        f"Appending the first {cfg['classification']['report_words']} words of each incident's longest linked report to the text gives macro-F1 {_ci(ab)} against {_ci(base)} for title + description alone "
        f"(same model, same folds). {'Longer text does not clearly help.' if ab['ci_low'] <= base['macro_f1'] <= ab['ci_high'] else ('Longer text helps.' if ab['macro_f1'] > base['macro_f1'] else 'Longer text hurts.')} "
        "Only the TF-IDF model was tried; the embedding models truncate long input anyway.\n"
    )
    add("## 3. Deployable model and calibration\n")
    add(f"**{res.deployable}.** {res.deployable_reason[0].upper() + res.deployable_reason[1:]}.\n")
    gap = sig[
        (sig["model_a"] == res.deployable) & (sig["model_b"] == BASELINE) & (sig["setting"] == "cv")
    ]
    if len(gap) and gap.iloc[0]["ci_low"] < 0.01 and res.deployable != BASELINE:
        add(
            f"*Caveat:* the lower end of that interval is only {gap.iloc[0]['ci_low']:+.3f} and the exact McNemar test on accuracy is not significant (p = {gap.iloc[0]['mcnemar_p']:.2f}), so the advantage is borderline in cross-validation; "
            "it is clearer in the time split. The cost of choosing it is that inference needs the sentence-embedding model (a one-off download, then cached locally; the dashboard must be run with that cache present to work offline).\n"
        )
    add("### Calibration of the confidence shown to users\n")
    names = {
        "raw": "uncalibrated",
        "sigmoid": "Platt (sigmoid)",
        "temperature": "temperature scaling",
    }
    table = pd.DataFrame(
        {
            names[m]: [
                cal[m]["ece"],
                cal[m]["brier"],
                cal[m]["accuracy"],
                cal[m]["mean_confidence"],
                cal[m]["macro_f1"],
            ]
            for m in names
        },
        index=[
            "expected calibration error (10 bins)",
            "Brier score",
            "accuracy",
            "mean confidence",
            "macro-F1",
        ],
    ).round(3)
    add(to_markdown(table, index=True))
    add("")
    chosen = cal["chosen"]
    over = cal["raw"]["mean_confidence"] - cal["raw"]["accuracy"]
    add(
        f"All options are evaluated on out-of-fold predictions with calibration fitted inside each training part (inner 3-fold CV), so no test fold influences them. "
        f"The uncalibrated model is "
        f"{'slightly over-confident' if over > 0.02 else 'slightly under-confident' if over < -0.02 else 'already close to calibrated'} "
        f"(mean confidence {cal['raw']['mean_confidence']:.3f} vs accuracy {cal['raw']['accuracy']:.3f}). "
        f"Platt scaling (one-vs-rest sigmoids renormalised over seven classes) {'improves' if cal['sigmoid']['ece'] < cal['raw']['ece'] else 'worsens'} ECE ({cal['raw']['ece']:.3f} -> {cal['sigmoid']['ece']:.3f}); "
        f"temperature scaling (one parameter, fitted T = {f['temperature']:.2f} for the final model if selected) gives {cal['temperature']['ece']:.3f}. "
        f"Rule fixed in advance: keep the uncalibrated model unless a calibrator lowers ECE by more than 0.005. **Selected: {names[chosen]}.** "
        + (
            "Temperature scaling does not change the predicted class, so macro-F1 is unchanged."
            if chosen == "temperature"
            else ""
        )
        + "\n"
    )
    add(
        _figure(
            "fig_rq3_4_reliability",
            "Reliability of the predicted domain's confidence for each calibration option",
            snap,
        )
    )
    add("## 4. Error analysis\n")
    add(
        f"Row-normalised confusion matrix of the best cross-validated model ({best}); rows are the MIT label.\n"
    )
    add(_figure("fig_rq3_2_confusion", "Confusion matrix (out-of-fold)", snap))
    add(
        "### Most frequent confusions (deployable model, calibrated confidence), with the most confidently wrong examples\n"
    )
    add(to_markdown(res.confusions_top.round(3)))
    add("")
    add(
        "Because the labels are machine-generated, a 'confusion' is as likely to be an automatic-labelling inconsistency as a classifier error; section 5 tests this with confident learning.\n"
    )
    add("### Highest-weight terms per domain (linear models fitted on all labelled incidents)\n")
    add(to_markdown(res.features[res.features["model"] == BASELINE][["domain", "top_terms"]]))
    add("")
    if res.reliability is not None:
        _reliability_section(res, add, snap)
    add("## 6. Fine-tuning DistilBERT (local GPU; Colab as the documented alternative)\n")
    add(
        "`scripts/train_distilbert_local.py` runs the training code in `scripts/colab_distilbert_code.py` on the local NVIDIA GPU; `notebooks/colab_distilbert_finetune.ipynb` embeds the same file verbatim for Colab. "
        "Both read `reports/colab/rq3_colab_input.csv` (incident id, text, label, fold, time-split flag), train one model per fold and one for the time split with a protocol fixed in advance "
        "(4 epochs, lr 5e-5, batch 16, max length 128, class-weighted loss, seed 42 + fold), and write `reports/colab/rq3_distilbert_predictions.csv`. "
        "The loader checks that the incidents, labels and folds in that file match this repository exactly before scoring it. Run details (GPU, versions, minutes) are in `reports/colab/rq3_distilbert_run.json`.\n"
    )
    add("## 7. Limitations\n")
    add(
        "- **Machine-generated target.** High accuracy would mean the text predicts an automatic labeller, not that the labels are right; section 5 assesses the labels against independent signals.\n"
        "- **Small classes.** The smallest domain has 24 incidents; per-class results and the macro-F1 depend heavily on a handful of cases, and bootstrap CIs resample incidents, not model fits.\n"
        "- **Same data for everything.** Pooled out-of-fold predictions are slightly pessimistic estimates of a model trained on all data; the CIs ignore fold-to-fold variation in model fitting (reported separately as per-fold sd).\n"
        "- **Time split is a shift test.** Class mix and topics change after 2023 (Phase 1/3/4 findings), and 2024+ incidents with MIT labels are a non-random subset (coverage falls for recent incidents).\n"
        "- **Texts are short** (about 50 words); embedding and TF-IDF models see the same title + description.\n"
        "- **Calibration** is assessed on the same cross-validation folds with 10 bins; bins at high confidence are sparse.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    logger.info("Wrote %s", path)


def _reliability_section(res: ClassificationResults, add: Any, snap: str) -> None:
    """Section 5: how reliable are the AI-generated (MIT) labels? Three checks side by side."""
    r = res.reliability
    rf = r.facts
    add("## 5. How reliable are the AI-generated (MIT) labels?\n")
    add(
        "No hand annotation is used (decision D1 in `docs/decisions.md`). Instead three complementary checks use independent signals already in AIID. "
        "Each is partial on its own; together they show where the automatic labels can be trusted and where they cannot.\n"
    )
    add(
        _figure(
            "fig_rq3_5_label_reliability",
            "Three reliability checks of the MIT risk-domain labels",
            snap,
        )
    )
    # (a)
    add("### (a) Agreement with human annotations already in AIID (CSETv1, GMF)\n")
    add(
        f"CSETv1 annotations exist for {n(rf['cset_mit_overlap'])} MIT-labelled incidents (all from {rf['cset_year_max']} or earlier) and GMF for {n(rf['gmf_mit_overlap'])}. "
        "No human field is a risk-domain label, so each comparison maps one MIT domain to the human field closest to it in meaning and compares the two yes/no answers. "
        "**These are partial, convergent-validity checks, not ground truth:** low agreement can come from definitional mismatch as much as from labelling error. "
        "Rows where the human field is 'maybe', 'unclear' or empty are excluded (column `excluded_unclear`). Kappa CIs are percentile bootstrap (2,000 resamples of incidents).\n"
    )
    m = r.mappings.copy()
    m["kappa [95% CI]"] = m.apply(
        lambda x: f"{x['kappa']:.2f} [{x['kappa_low']:.2f}, {x['kappa_high']:.2f}]", axis=1
    )
    m["agreement"] = m["agreement"].map(pct)
    add(
        to_markdown(
            m[
                [
                    "mit_domain",
                    "human_field",
                    "n",
                    "excluded_unclear",
                    "mit_positive",
                    "human_positive",
                    "agreement",
                    "kappa [95% CI]",
                    "band",
                    "rationale",
                ]
            ]
        )
    )
    add("")
    add(
        "Reading: where the MIT domain and the human field describe the same thing (discrimination vs protected characteristic or harm distribution), agreement is substantial. "
        "Where the concepts only overlap (AI-system safety vs tangible harm; misinformation/misuse vs detrimental content) agreement is moderate or fair, which is what partial overlap predicts. "
        "The GMF comparison has too few incidents to say anything (its CI spans zero).\n"
    )
    # (b)
    ps, pd_ = rf["pairs_similar"], rf["pairs_dissimilar"]
    add("### (b) Consistency on editor-linked pairs\n")
    add(
        f"AIID editors marked {n(ps['pairs_total'])} pairs of incidents as similar (the RQ4 ground truth); in {n(ps['pairs_labelled'])} both incidents have an MIT label. "
        f"**{pct(ps['same_domain_rate'])} of them share the same MIT domain** (95% CI {pct(ps['ci_low'])}-{pct(ps['ci_high'])}), against {pct(ps['baseline_rate'])} "
        f"(95% range {pct(ps['baseline_low'])}-{pct(ps['baseline_high'])}) for random pairs matched on the two incidents' years (2,000 permutations; p = {ps['p_value']:.4f}; {ps['lift']:.1f} times the baseline). "
        f"For the {n(pd_['pairs_labelled'])} pairs editors marked as *dissimilar*, the rate is {pct(pd_['same_domain_rate'])}, close to its own random baseline of {pct(pd_['baseline_rate'])} (p = {pd_['p_value']:.2f}). "
        "So the automatic labels follow human editorial judgement about which incidents belong together. "
        "Similar incidents need not share a domain (a deepfake used for a scam is both misuse and misinformation), so 100% is not the target.\n"
    )
    add("Most frequent domain combinations among editor-similar pairs whose MIT domains differ:\n")
    add(to_markdown(r.pair_domains.head(6)))
    add("")
    # (c)
    add("### (c) Confident learning (Northcutt et al., 2021)\n")
    add(
        f"Out-of-fold probabilities of the best classifier ({rf['cl_model']}, temperature-scaled) are used to estimate the joint distribution of given and latent labels "
        "(cleanlab, default settings: per-class confidence thresholds, `prune_by_noise_rate`). "
        f"**Estimated share of wrong labels: {pct(rf['cl_noise_rate'])}**; {n(rf['cl_flagged'])} incidents ({pct(rf['cl_flagged_share'])}) are flagged as likely mislabelled "
        "(`reports/tables/rq3rel_flagged_incidents.csv`, most suspicious first). The estimate inherits the classifier's own errors: a flag means 'the text points elsewhere', not proof of a wrong label.\n"
    )
    nb = r.cl.noise_by_domain.copy()
    nb["estimated_noise_rate"] = nb["estimated_noise_rate"].map(pct)
    nb["flagged_share"] = nb["flagged_share"].map(pct)
    add(to_markdown(nb))
    add("")
    add(
        _figure(
            "fig_rq3_6_label_confusion",
            "Estimated incidents whose given MIT label is likely another domain",
            snap,
        )
    )
    sym = r.symmetric.head(6).copy()
    add("Confusion structure (estimated incidents, both directions):\n")
    add(to_markdown(sym.round(1)))
    add("")
    top, second = sym.iloc[0], sym.iloc[1]
    add(
        f"**Taxonomy overlap or labelling error?** The largest exchange is between {top['domain_a']} and {top['domain_b']} "
        f"({top['total']:.0f} estimated incidents: {top['a_to_b']:.0f} one way, {top['b_to_a']:.0f} the other). For this pair MIT's own taxonomy allows either label "
        "(AI-generated disinformation and deepfake scams are both deliberate misuse and false content), and the lopsided direction suggests the automatic labeller "
        "applies a consistent preference rather than making random errors: mostly a taxonomy-overlap effect. "
        f"The next exchange, {second['domain_a']} vs {second['domain_b']} ({second['total']:.0f} incidents), joins domains that are conceptually further apart, "
        "so it is more likely to reflect inconsistent labelling. The two smallest domains (Human-Computer Interaction, Socioeconomic & Environmental Harms) have the highest "
        "estimated noise rates, matching their low classifier F1: their boundaries are the least clear in the incident text.\n"
    )
    # retrain
    rt = r.retrain
    prim = rt.iloc[0]
    add("### Sensitivity: retraining without likely mislabelled incidents\n")
    add(
        f"To avoid leakage, flags are recomputed inside every training part (inner 5-fold cross-validation, then confident learning on the training incidents only; {pct(rf['retrain_removed_share'])} of training incidents removed on average); "
        "the model is refitted without them and evaluated on the untouched outer test fold, with the original MIT labels. "
        f"Macro-F1 on all {n(int(prim['n']))} incidents: {prim['macro_f1_original']:.3f} originally, {prim['macro_f1_cleaned_training']:.3f} with cleaned training data "
        f"(difference {prim['difference']:+.3f}, 95% CI [{prim['ci_low']:+.3f}, {prim['ci_high']:+.3f}], paired bootstrap p = {prim['p_value']:.3f}). "
        + (
            "Removing suspected label noise from training does not significantly change performance on the original labels. "
            if prim["ci_low"] <= 0 <= prim["ci_high"]
            else (
                "Removing suspected label noise from training improves performance on the original labels, consistent with some genuine label noise. "
                if prim["difference"] > 0
                else "Removing suspected label noise from training lowers performance on the original labels. "
            )
        )
        + "This is a sensitivity check of the reliability finding, not a way to report a higher score: the headline classifier results above are unchanged. "
        "(A first, non-nested version flagged incidents once on all data and appeared to gain about 0.04, but there the test labels influenced which training incidents were removed; "
        "the nested design above removes that leak.)\n"
    )
    show = rt.copy()
    add(to_markdown(show.round(3)))
    add("")
