"""Post-annotation analysis of the RQ3 label audit: tables, figure, registry entries and docs/rq3_label_audit.md.

Runs only when `data/manual/label_audit_sample.csv` contains your annotations; with none it reports that and exits.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import pandas as pd

from aicidentia import registry
from aicidentia.config import PROJECT_ROOT, load_config
from aicidentia.data import clean
from aicidentia.data.audit_docs import n, pct
from aicidentia.models import classify as C
from aicidentia.models import label_audit as A
from aicidentia.viz import plots, style
from aicidentia.viz.style import to_markdown

logger = logging.getLogger(__name__)
PRODUCER = "aicidentia.models.label_audit_outputs.run_audit_analysis"
SOURCE = "data/manual/label_audit_sample.csv"


def run_audit_analysis(path: Path = A.SAMPLE_PATH) -> dict[str, Any] | None:
    """Compare your annotations with the MIT labels and the classifier; None if nothing is annotated yet."""
    data = C.load_dataset(with_embeddings=False)
    progress = A.annotation_progress(path, data.classes)
    if progress["labelled"] == 0:
        logger.warning("No recognised annotations in %s yet", path.name)
        return None
    annotations = A.load_annotations(path, data.classes)
    key = pd.read_parquet(A.KEY_PATH)
    predictions = clean.load_processed("rq3_domain_predictions")
    model = predictions[predictions["source"] == "out_of_fold"][
        ["incident_id", "predicted_domain"]
    ].rename(columns={"predicted_domain": "predicted"})
    result = A.audit_analysis(
        annotations,
        key,
        data.frame["domain"].value_counts(),
        data.classes,
        model,
        int(load_config()["classification"]["n_boot"]) * 2,
    )
    result["progress"] = progress
    result["unrecognised"] = progress["unrecognised"]
    return result


def write_all(result: dict[str, Any], classes: list[str]) -> None:
    """Registry, tables, figure and docs/rq3_label_audit.md."""
    scalars = {
        k: v
        for k, v in result.items()
        if k
        in (
            "n_annotated",
            "population",
            "complete",
            "agreement_raw",
            "agreement_design_weighted",
            "kappa_raw",
            "kappa_raw_ci",
            "kappa_raw_band",
            "kappa_weighted",
            "kappa_weighted_ci",
            "kappa_weighted_band",
            "classifier",
            "unrecognised",
        )
    }
    for key, value in scalars.items():
        registry.record(f"rq3audit.{key}", value, SOURCE, PRODUCER)
    style.save_table(result["confusion"], "rq3audit_confusion_counts", index=True)
    style.save_table(result["per_domain"].round(3), "rq3audit_per_domain")
    style.save_table(result["by_confidence"].round(3), "rq3audit_by_confidence")
    norm = result["confusion"].div(result["confusion"].sum(axis=1).clip(lower=1), axis=0)
    fig = plots.plot_confusion_heatmap(
        norm,
        "MIT label vs your label (row-normalised)",
        "Your label",
        "MIT label (machine-generated)",
    )
    style.save_figure(fig, "fig_rq3audit_1_mit_vs_human", str(load_config()["snapshot_date"]))
    write_doc(result, PROJECT_ROOT / "docs" / "rq3_label_audit.md")


def write_doc(r: dict[str, Any], path: Path) -> None:
    """docs/rq3_label_audit.md."""
    snap = str(load_config()["snapshot_date"])
    L: list[str] = []
    add = L.append
    add("# RQ3: label audit, MIT labels vs your blind judgement\n")
    add(
        f"_Auto-generated by `aicidentia.models.label_audit_outputs` (AIID snapshot **{snap}**). Your annotations are in `data/manual/label_audit_sample.csv`._\n"
    )
    if not r["complete"]:
        add(
            f"> **PARTIAL:** {r['n_annotated']} of {r['progress']['rows']} items annotated; {r['unrecognised']} label entries could not be matched to a domain name. Re-run after finishing.\n"
        )
    add("## Summary\n")
    add(
        f"- **Agreement between the machine-generated MIT label and your label:** {pct(r['agreement_raw'])} of the {r['n_annotated']} annotated sample items; "
        f"{pct(r['agreement_design_weighted'])} after weighting to the population of {n(r['population'])} labelled incidents (the sample over-represents small domains on purpose).\n"
        f"- **Cohen's kappa (sample):** {r['kappa_raw']:.3f}, bootstrap 95% CI [{r['kappa_raw_ci'][0]:.3f}, {r['kappa_raw_ci'][1]:.3f}]: **{r['kappa_raw_band']}** (Landis & Koch, 1977).\n"
        f"- **Cohen's kappa (design-weighted, population estimate):** {r['kappa_weighted']:.3f}, 95% CI [{r['kappa_weighted_ci'][0]:.3f}, {r['kappa_weighted_ci'][1]:.3f}]: **{r['kappa_weighted_band']}**.\n"
    )
    if "classifier" in r:
        c = r["classifier"]
        add(
            f"- **Classifier vs you** (out-of-fold predictions of the deployable model on the same {c['n']} items): kappa(MIT, you) = {c['kappa_mit_vs_human']:.3f}, kappa(classifier, you) = {c['kappa_model_vs_human']:.3f}, "
            f"kappa(classifier, MIT) = {c['kappa_model_vs_mit']:.3f}. "
            + (
                "The classifier agrees with you about as well as the MIT labels do."
                if abs(c["kappa_model_vs_human"] - c["kappa_mit_vs_human"]) < 0.05
                else "The classifier agrees with you "
                + ("better" if c["kappa_model_vs_human"] > c["kappa_mit_vs_human"] else "worse")
                + " than the MIT labels do."
            )
            + "\n"
        )
    add("## Interpretation (read with the limitations below)\n")
    add(
        "Landis & Koch bands: below 0 poor; 0-0.20 slight; 0.21-0.40 fair; 0.41-0.60 moderate; 0.61-0.80 substantial; 0.81-1 almost perfect. "
        "Kappa is chance-corrected and depends on class prevalence, so the design-weighted value is the better estimate for the whole database, and the raw-sample value describes this particular balanced sample.\n"
    )
    add("## Confusion: MIT (rows) vs you (columns), counts\n")
    add(to_markdown(r["confusion"], index=True))
    add("")
    add("![MIT label vs your label](../reports/figures/fig_rq3audit_1_mit_vs_human.png)\n")
    add(f"*Figure: MIT label vs your label. Source: AIID snapshot {snap}.*\n")
    add("## Agreement per MIT domain\n")
    add(to_markdown(r["per_domain"].round(3)))
    add(
        "\n`agreement_of_reference` = share of items MIT put in this domain that you also put there; `agreement_of_other` = share of items you put there that MIT also did.\n"
    )
    add("## Agreement by your confidence\n")
    add(to_markdown(r["by_confidence"].round(3)))
    add("")
    add("## Limitations\n")
    add(
        "- **One annotator.** Disagreement mixes MIT labelling errors with your own errors and with genuine ambiguity between domains; with one person there is no inter-annotator reliability to separate these.\n"
        "- **Domains overlap** (for example fraud using deepfakes can be 'Malicious Actors & Misuse', 'Misinformation' or 'Privacy & Security'), so some disagreement reflects the taxonomy, not either labeller.\n"
        "- **Small sample** (150), and as few as 10 items in the smallest domains: per-domain agreement has wide uncertainty; kappa CIs are bootstrap percentile intervals.\n"
        "- **Design weighting** assumes the sample is a simple random draw within each MIT domain.\n"
        "- **Title and description only**: MIT's automatic labeller may have used other text; you saw only what is in the file.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
