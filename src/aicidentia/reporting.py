def resolve(reference: str) -> Any:
    key, _, path = reference.partition(":")
    value = registry.get(key)
    for part in re.findall(r"\[[^\]]*\]|[^.\[\]]+", path):
        if part.startswith("["):
            conditions = dict(c.split("=", 1) for c in part[1:-1].split(";"))
            value = next(
                row for row in value if all(str(row.get(k)) == v for k, v in conditions.items())
            )
        else:
            value = value[part]
    return value


def _fmt(value: Any, fmt: str) -> str:
    if isinstance(value, list):
        if value and isinstance(value[0], dict):
            return f"table ({len(value)} rows)"
        return "; ".join(str(v) for v in value)
    try:
        return fmt.format(value)
    except (ValueError, TypeError):
        return str(value)


def write_report_facts(path: Any = None) -> int:
    path = path or PROJECT_ROOT / "docs" / "report_facts.md"
    results = registry.load_results()
    snap = load_config()["snapshot_date"]
    lines = [
        "# Report facts\n",
        f"_Fact sheet generated by `aicidentia.reporting` from `reports/results.json` (AIID snapshot {snap}). "
        "Every value is read live from the registry; cite the key. No interpretation here: see the RQ documents and "
        "`docs/decisions.md`._\n",
    ]
    count = 0
    for title, facts in SECTIONS:
        lines += [
            f"## {title}\n",
            "| Fact | Value | results.json key | Source file |",
            "|---|---|---|---|",
        ]
        for label, reference, fmt in facts:
            key = reference.split(":")[0]
            try:
                value = _fmt(resolve(reference), fmt)
            except (KeyError, StopIteration, IndexError, TypeError):
                value = "(missing)"
            source = results.get(key, {}).get("source_file", "")
            lines.append(f"| {label} | {value} | `{reference}` | `{source}` |")
            count += 1
        lines.append("")
    lines += [
        "## Key findings\n",
        "See `docs/key_findings.md` (generated from `story.key_findings`).\n",
        "## Tables and figures\n",
        "Tables: `reports/tables/<name>.csv` and `.md`. Figures: `reports/figures/<name>.png` (300 dpi) and `.svg`, "
        "at IEEE widths 3.5 in (single column) or 7.16 in (double column). Dashboard screenshots: `reports/figures/dashboard/`.\n",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return count
