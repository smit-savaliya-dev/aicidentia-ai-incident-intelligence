"""Write docs/environment.md: OS, hardware, Python version and every installed package.

Usage:  uv run python scripts/generate_environment_doc.py
"""

from __future__ import annotations

import platform
import subprocess
import sys
from datetime import UTC, datetime
from importlib import metadata

from aicidentia.config import PROJECT_ROOT


def torch_summary() -> list[str]:
    try:
        import torch
    except ImportError:
        return ["- torch: not installed"]
    lines = [f"- torch build: `{torch.__version__}` (CUDA runtime: {torch.version.cuda})"]
    if torch.cuda.is_available():
        lines.append(f"- CUDA available: yes - {torch.cuda.get_device_name(0)}")
    else:
        lines.append("- CUDA available: no (CPU only)")
    return lines


def nvidia_driver() -> str | None:
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=name,driver_version,memory.total", "--format=csv,noheader"],
            capture_output=True,
            text=True,
            timeout=15,
            check=True,
        )
        return out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        return None


def main() -> None:
    packages = sorted(
        {(d.metadata["Name"], d.version) for d in metadata.distributions()},
        key=lambda x: x[0].lower(),
    )
    lines = [
        "# Environment",
        "",
        "_Auto-generated by `scripts/generate_environment_doc.py`. Do not edit by hand._",
        "",
        f"Generated (UTC): {datetime.now(UTC).strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "## System",
        "",
        f"- OS: {platform.system()} {platform.release()} ({platform.version()})",
        f"- Machine: {platform.machine()}",
        f"- Processor: {platform.processor()}",
        f"- Python: {sys.version.split()[0]} ({platform.python_implementation()})",
        f"- Interpreter: `{sys.executable}`",
    ]
    gpu = nvidia_driver()
    lines.append(f"- NVIDIA GPU (name, driver, memory): {gpu or 'none detected'}")
    lines += torch_summary()
    lines += [
        "",
        f"## Installed packages ({len(packages)})",
        "",
        "| Package | Version |",
        "|---------|---------|",
    ]
    lines += [f"| {name} | {version} |" for name, version in packages]
    out = PROJECT_ROOT / "docs" / "environment.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out.relative_to(PROJECT_ROOT)} ({len(packages)} packages)")


if __name__ == "__main__":
    main()
