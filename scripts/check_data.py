"""Check the AIID files in data/raw/ and record them in docs/data_manifest.md.

* Looks for the Excel export (required) and the .tar.bz2 snapshot (optional).
* Records each file's SHA-256 and the snapshot date in docs/data_manifest.md.
* Prints every Excel sheet with its row and column counts.
* Safely extracts the snapshot into data/raw/snapshot_<date>/ (tarfile filter="data").

Usage:  uv run python scripts/check_data.py [--strict] [--force-extract]
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import sys
import tarfile
from datetime import UTC, datetime
from pathlib import Path

from aicidentia.config import PROJECT_ROOT, load_config
from aicidentia.data import load

EXCEL_DATE_RE = re.compile(r"(\d{8})")
SNAPSHOT_DATE_RE = re.compile(r"(\d{8})(\d{6})?")


def sha256_of(path: Path, chunk: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        while block := fh.read(chunk):
            digest.update(block)
    return digest.hexdigest()


def find_latest(raw_dir: Path, pattern: str) -> Path | None:
    matches = sorted(raw_dir.glob(pattern))
    if len(matches) > 1:
        print(
            f"  WARNING: {len(matches)} files match {pattern!r}; using the latest: {matches[-1].name}"
        )
    return matches[-1] if matches else None


def date_from_name(path: Path, regex: re.Pattern[str]) -> str | None:
    match = regex.search(path.name)
    return match.group(1) if match else None


def describe_excel(path: Path) -> list[tuple[str, int, int]]:
    """Rows/columns per sheet with banner rows removed (same loader the analysis uses)."""
    rows = []
    for name in load_config()["files"]["excel_sheets"]:
        try:
            df = load.load_sheet(name, path)
        except (ValueError, KeyError):
            continue
        rows.append((name, df.shape[0], df.shape[1]))
    print(f"  {'Sheet':<20}{'Rows':>10}{'Columns':>10}")
    for name, n_rows, n_cols in rows:
        print(f"  {name:<20}{n_rows:>10}{n_cols:>10}")
    return rows


def extract_snapshot(archive: Path, dest: Path, force: bool) -> list[Path]:
    if dest.exists() and any(dest.iterdir()) and not force:
        print(
            f"  {dest.relative_to(PROJECT_ROOT)} already exists - skipping extraction (use --force-extract)."
        )
    else:
        dest.mkdir(parents=True, exist_ok=True)
        try:
            with tarfile.open(archive, "r:bz2") as tar:
                tar.extractall(dest, filter="data")  # safe extraction: rejects unsafe members
        except (tarfile.TarError, OSError, EOFError) as exc:
            shutil.rmtree(dest, ignore_errors=True)  # do not leave a half-extracted snapshot
            print(f"\n[ERROR] Could not safely extract {archive.name}: {exc}")
            print("        Partial output removed; the manifest was not changed.")
            raise SystemExit(1) from exc
        print(f"  Extracted to {dest.relative_to(PROJECT_ROOT)}")
    files = sorted(p for p in dest.rglob("*") if p.is_file())
    print(f"  {len(files)} files in snapshot:")
    for p in files:
        print(f"    {p.relative_to(dest).as_posix()}  ({p.stat().st_size / 1e6:.2f} MB)")
    return files


def write_manifest(
    path: Path,
    excel: Path,
    excel_date: str | None,
    sheets: list[tuple[str, int, int]],
    snapshot: Path | None,
    snapshot_date: str | None,
    snapshot_files: list[Path],
    snapshot_dir: Path | None = None,
) -> None:
    lines = [
        "# Data manifest",
        "",
        "_Auto-generated by `scripts/check_data.py`. Do not edit by hand._",
        "",
        f"Generated (UTC): {datetime.now(UTC).strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "| File | Required | Snapshot date | SHA-256 | Size (bytes) |",
        "|------|----------|---------------|---------|--------------|",
        f"| `{excel.name}` | yes | {excel_date or 'unknown'} | `{sha256_of(excel)}` | {excel.stat().st_size} |",
    ]
    if snapshot is not None:
        lines.append(
            f"| `{snapshot.name}` | no | {snapshot_date or 'unknown'} | `{sha256_of(snapshot)}` | "
            f"{snapshot.stat().st_size} |"
        )
    elif snapshot_dir is None:
        lines.append("| _(backup-*.tar.bz2 not present)_ | no | - | - | - |")
    lines += ["", "## Excel sheets", "", "| Sheet | Rows | Columns |", "|-------|------|---------|"]
    lines += [f"| {name} | {r} | {c} |" for name, r, c in sheets]
    if snapshot is not None and snapshot_files:
        lines += ["", f"## Snapshot contents ({len(snapshot_files)} files)", ""]
        lines += [f"- `{p.name}`" for p in snapshot_files]
    if snapshot_dir is not None:
        files = sorted(p for p in snapshot_dir.rglob("*") if p.is_file())
        hashes = {p.relative_to(snapshot_dir).as_posix(): sha256_of(p) for p in files}
        joined = "\n".join(f"{k}:{v}" for k, v in hashes.items())
        tree = hashlib.sha256(joined.encode()).hexdigest()
        lines += [
            "",
            f"## Extracted snapshot directory `{snapshot_dir.name}/` ({len(files)} files)",
            "",
            "No `.tar.bz2` archive is present; the dump was extracted manually, and its directory name carries no date.",
            f"Tree hash (SHA-256 of sorted `path:sha256` lines): `{tree}`",
            "",
            "| File | Size (bytes) | SHA-256 |",
            "|------|--------------|---------|",
        ]
        lines += [
            f"| `{k}` | {(snapshot_dir / k).stat().st_size} | `{v}` |" for k, v in hashes.items()
        ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--strict", action="store_true", help="exit 1 if the Excel export is missing"
    )
    parser.add_argument("--force-extract", action="store_true", help="re-extract the snapshot")
    args = parser.parse_args()

    cfg = load_config()
    raw_dir = PROJECT_ROOT / cfg["paths"]["raw"]
    manifest = PROJECT_ROOT / cfg["paths"]["manifest"]
    print(f"AICIDENTIA data check - looking in {raw_dir.relative_to(PROJECT_ROOT)}/")

    excel = find_latest(raw_dir, cfg["files"]["excel_export_glob"]) if raw_dir.exists() else None
    snapshot = find_latest(raw_dir, cfg["files"]["snapshot_glob"]) if raw_dir.exists() else None

    if excel is None:
        print(
            f"\n[MISSING] Excel export ({cfg['files']['excel_export_glob']}) not found in data/raw/."
        )
        print("          Download it from the AI Incident Database and place it there.")
    snapshot_dir = load.find_snapshot_dir(raw_dir) if raw_dir.exists() else None
    if snapshot is None and snapshot_dir is None:
        print(
            f"[MISSING] Snapshot ({cfg['files']['snapshot_glob']}) not found in data/raw/ - optional."
        )
        print(
            "          It is only needed for full article text and editor-marked similar incidents."
        )

    if excel is None:
        print("\nNo data to check. The manifest was not changed.")
        return 1 if args.strict else 0

    excel_date = date_from_name(excel, EXCEL_DATE_RE)
    print(f"\n[FOUND] {excel.name}  (export date: {excel_date or 'unknown'})")
    sheets = describe_excel(excel)
    configured = cfg.get("snapshot_date")
    if configured is None or str(configured) != str(excel_date):
        print(
            f"  NOTE: config snapshot_date is {configured!r}; set it to {excel_date!r} in config/config.yaml."
        )
    expected = set(cfg["files"]["excel_sheets"])
    missing_sheets = expected - {name for name, _, _ in sheets}
    if missing_sheets:
        print(f"  WARNING: expected sheets not found: {sorted(missing_sheets)}")

    snapshot_files: list[Path] = []
    snapshot_date = None
    if snapshot is not None:
        snapshot_date = date_from_name(snapshot, SNAPSHOT_DATE_RE)
        print(f"\n[FOUND] {snapshot.name}  (snapshot date: {snapshot_date or 'unknown'})")
        dest = raw_dir / f"snapshot_{snapshot_date or 'unknown'}"
        snapshot_files = extract_snapshot(snapshot, dest, args.force_extract)

    manifest_dir = None
    if snapshot is None and snapshot_dir is not None:
        manifest_dir = snapshot_dir
        print(f"\n[FOUND] extracted snapshot directory {snapshot_dir.name}/ (no archive present)")
        for p in sorted(snapshot_dir.glob("*")):
            print(f"    {p.name}{'/' if p.is_dir() else ''}")

    write_manifest(
        manifest, excel, excel_date, sheets, snapshot, snapshot_date, snapshot_files, manifest_dir
    )
    print(f"\nManifest written to {manifest.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
